export function roleById(id: RoleId) {
  return ROLES.find((r) => r.id === id)!;
}

export function userForRole(id: RoleId) {
  return USERS.find((u) => u.role === id && u.status === "Active")!;
}

export function can(role: RoleId, permission: Permission) {
  return roleById(role).permissions.includes(permission);
}

export function canModule(role: RoleId, module: string) {
  const r = roleById(role);
  if (r.modules.includes("all") || r.modules.includes("portal") && module === "portal") return true;
  if (r.modules.includes("all")) return true;
  return r.modules.includes(module);
}
