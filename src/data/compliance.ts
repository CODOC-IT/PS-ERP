function doc(
  id: string,
  employeeId: string,
  type: string,
  number: string,
  issueDate: string,
  expiryDate: string | null,
  issuer: string,
  verification: DocumentRecord["verification"],
  uploadedBy: string,
  version: number,
): DocumentRecord {
  return {
    id,
    employeeId,
    type,
    number,
    issueDate,
    expiryDate,
    issuer,
    fileName: number ? `${type.replace(/ /g, "-")}-${number}.pdf` : "",
    verification,
    uploadedBy,
    uploadedDate: issueDate || "2026-08-10",
    version,
  };
}

